"""Create the PUBLIC demo file used for online testing.

Starts from the synthetic workload demo (data/TestStudents_demo.xlsx) and replaces
all student identifiers with made-up ones, so nothing in the published file can be
linked back to a real student:

  * PIDM -> random unique 7-digit number
  * ZID  -> "Z9" + random unique 7 digits
  * row order shuffled

Programs, majors and demographic fields are kept so the dashboards stay realistic.
Only this file is committed to GitHub; the files with original IDs stay local
(see .gitignore).

Usage:  python scripts/make_public_demo.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "TestStudents_demo.xlsx"
OUT = ROOT / "data" / "EduNexus_public_demo.xlsx"
SEED = 7341


def build(src: Path = SRC, out: Path = OUT, seed: int = SEED) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    df = pd.read_excel(src, sheet_name=0)
    n = len(df)
    df = df.sample(frac=1, random_state=seed).reset_index(drop=True)
    pidm = rng.choice(np.arange(1_000_000, 9_999_999), size=n, replace=False)
    zid = rng.choice(np.arange(1_000_000, 9_999_999), size=n, replace=False)
    df["PIDM"] = pidm
    df["ZID"] = [f"Z9{z:07d}" for z in zid]

    note = pd.DataFrame({"About this file": [
        "PUBLIC DEMO DATA - SYNTHETIC. Safe for online testing.",
        "PIDM and ZID are randomly generated and do not belong to any real student.",
        "COURSES, CREDIT_HOURS, BILL_HOURS and WITHDRAWALS are synthetic (credit-load policy compliant).",
        "Programs, majors, levels and demographic mix are kept for realistic dashboards.",
        f"Generated by scripts/make_public_demo.py (seed {seed}). Not for reporting.",
    ]})
    with pd.ExcelWriter(out, engine="openpyxl") as xw:
        df.to_excel(xw, sheet_name="Students", index=False)
        note.to_excel(xw, sheet_name="README_SYNTHETIC", index=False)
    return df


if __name__ == "__main__":
    d = build()
    print(f"Wrote {OUT}: {len(d)} rows")
